import assert from 'node:assert/strict';
import { validateM8Preconditions } from '../../domain/simulation/m8Adapter';
import { resolveCapital } from '../../domain/simulation/capitalResolver';
import { DEFAULT_PARAMETERS } from '../../domain/model/defaults';
import { rebaseSimulationParams } from './rebaseSimulationParams';
import { rebaseSnapshotFx, sourceRebaseEngineIdentity } from './rebaseSnapshotEconomics';
import type { ManualAdjustmentImpact } from '../../domain/simulation/manualCapitalAdjustments';
import type { ModelParameters } from '../../domain/model/types';
const empty: ManualAdjustmentImpact = { currentTotalDelta: 0, currentBanksDelta: 0, currentInvestmentsDelta: 0, currentRiskDelta: 0, futureEvents: [], futureCapitalEvents: [] };
const impact: ManualAdjustmentImpact = { ...empty, currentTotalDelta: 30, currentBanksDelta: 10, currentInvestmentsDelta: 20,
    futureCapitalEvents: [{ id: 'manual-future', effectiveDate: '2028-01', amount: 100, currency: 'CLP', type: 'inflow' } as never] };
const base = structuredClone(DEFAULT_PARAMETERS);
base.capitalSource = 'aurum';
base.simulationComposition = { mode: 'full', optimizableInvestmentsCLP: 1000, totalNetWorthCLP: 2000,
    nonOptimizable: { banksCLP: 100, realEstate: { propertyValueCLP: 2000, mortgageDebtOutstandingCLP: 1000, ufSnapshotCLP: 40000 }, riskCapital: { totalCLP: 50, usdSnapshotCLP: 900, enabled: true } } } as never;
base.capitalInitial = 1100;
const context = { manualAdjustmentImpact: impact, riskCapitalEnabled: true, riskCapitalCLP: 50, riskCapitalUsdSnapshotCLP: 900,
    applyActiveDistribution: (p: ModelParameters) => p, resolveSimulationBaseMonth: () => '2026-06' };
const first = rebaseSimulationParams(base, base, { sourceBase: true }, context);
assert.equal(first.simulationComposition?.optimizableInvestmentsCLP, 1020);
assert.equal(first.simulationComposition?.nonOptimizable?.banksCLP, 110);
const updated = structuredClone(base);
updated.simulationComposition!.optimizableInvestmentsCLP = 1200;
updated.capitalInitial = 1300;
const edited = structuredClone(first);
edited.simulation.horizonMonths = 480;
edited.capitalSource = 'manual';
edited.manualCapitalInput = { financialCapitalCLP: 500 };
const next = rebaseSimulationParams(updated, edited, { sourceBase: true }, context);
assert.equal(next.simulationComposition?.optimizableInvestmentsCLP, 1220, 'manual delta applied once to new clean source');
assert.equal(next.simulationComposition?.nonOptimizable?.banksCLP, 110);
assert.equal(next.simulation.horizonMonths, 480, 'scenario edits survive');
assert.equal(next.capitalSource, 'aurum', 'applying an official base selects that source, rather than retaining a previous manual source');
assert.equal(next.manualCapitalInput, undefined);
assert.equal(next.futureCapitalEvents?.filter(e => e.id === 'manual-future').length, 1);
const repeated = rebaseSimulationParams(updated, next, { sourceBase: true }, context);
assert.deepEqual(repeated, next, 'reapplying same source neither duplicates nor subtracts adjustments');
const fxNew = structuredClone(updated);
fxNew.fx.clpUsdInitial = 950;
assert.equal(rebaseSnapshotFx(base, first, fxNew).clpUsdInitial, 950);
const fxOverride = structuredClone(first);
fxOverride.fx.clpUsdInitial = 930;
assert.equal(rebaseSnapshotFx(base, fxOverride, fxNew).clpUsdInitial, 930, 'manual FX override survives');
assert.equal(sourceRebaseEngineIdentity({ ...next, label: 'Other provenance' }), sourceRebaseEngineIdentity(next));
assert.equal(validateM8Preconditions(next, resolveCapital({ params: next })).ok, true, JSON.stringify(validateM8Preconditions(next, resolveCapital({ params: next }))));
assert.notEqual(sourceRebaseEngineIdentity({ ...next, simulation: { ...next.simulation, horizonMonths: next.simulation.horizonMonths + 12 } }), sourceRebaseEngineIdentity(next));
assert.notEqual(sourceRebaseEngineIdentity(first), sourceRebaseEngineIdentity(next));
const changedRisk = structuredClone(updated);
changedRisk.simulationComposition!.nonOptimizable!.riskCapital!.totalCLP = 75;
assert.equal(rebaseSimulationParams(changedRisk, next, { sourceBase: true }, context).simulationComposition?.nonOptimizable?.riskCapital?.totalCLP, 75, 'new source risk wins over previous React state');
console.log('Snapshot rebase: manual deltas, future events, scenarios and FX preservation passed');
